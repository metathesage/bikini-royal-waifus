import fs from 'node:fs';
import puppeteer from 'puppeteer-core';
const CHROME = ['C:/Program Files/BraveSoftware/Brave-Browser/Application/brave.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find((c) => fs.existsSync(c));
const [out, clip = 'Jog', t = '0.3'] = process.argv.slice(2);
const b = await puppeteer.launch({ executablePath: CHROME, headless: 'new', args: ['--no-sandbox', '--enable-gpu', '--use-angle=d3d11'] });
const p = await b.newPage(); await p.setViewport({ width: 900, height: 700 });
p.on('pageerror', (e) => console.log('pageerror', e.message)); p.on('console', (m) => { if (m.type() === 'error') console.log('console', m.text().slice(0, 200)); });
await p.goto(`http://localhost:5173/retarget.html?clip=${clip}&t=${t}`); await p.waitForFunction('window.__done', { timeout: 60000 });
console.log(await p.evaluate(() => JSON.stringify(window.__info)));
await new Promise((r) => setTimeout(r, 500)); await p.screenshot({ path: out }); await b.close();
